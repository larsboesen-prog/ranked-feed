// Writes ../descs.js (window.DESCS: [English, Spanish] by place id) from the descriptions here that are ready (apply !== false).
// /page2 and /page5 show these for places whose data has no description (20 Nov 2026). node mapsma/listings/build-descs.mjs
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
const HERE = fileURLToPath(new URL(".", import.meta.url));
const out = {};
for (const f of readdirSync(HERE).filter((f) => /^(descriptions|extras)-\d{4}-\d\d-\d\d\.json$/.test(f)).sort()) {
  for (const p of JSON.parse(readFileSync(HERE + f, "utf8")).places) {
    if (p.apply === false) continue;
    if (!p.desc || p.desc.length > 160 || !p.desc_es) throw new Error(`${f} ${p.id}: description missing or too long`);
    out[p.id] = [p.desc, p.desc_es];
  }
}
writeFileSync(HERE + "../descs.js", "/* Descriptions in English and Spanish for places on mapsma.com whose data has none (20 Nov 2026), shown by /page2 and /page5.\n"
  + "   Generated by mapsma/listings/build-descs.mjs from mapsma/listings/*.json (edit those). Once they are in data/*.json, this file can go. */\n"
  + "window.DESCS=" + JSON.stringify(out, null, 0).replace(/\],"/g, '],\n"') + ";\n");
console.log(Object.keys(out).length, "descriptions");
